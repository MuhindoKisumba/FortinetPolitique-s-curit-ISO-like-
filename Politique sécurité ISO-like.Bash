########################################################
1. OBJECTIF
########################################################

La présente politique définit les règles de sécurité
informatique de l’entreprise afin de :

- Protéger les données
- Garantir la confidentialité
- Garantir l’intégrité
- Garantir la disponibilité des systèmes
- Réduire les risques cyber
- Assurer la continuité des activités

Cette politique s’inspire des bonnes pratiques :
- ISO/IEC 27001
- ISO/IEC 27002
- NIST Cybersecurity Framework
- CIS Controls

========================================================
2. CHAMP D’APPLICATION
========================================================

Cette politique s’applique à :

- Tous les employés
- Tous les consultants
- Tous les prestataires
- Tous les équipements informatiques
- Tous les serveurs
- Tous les réseaux
- Tous les accès VPN
- Tous les équipements mobiles

========================================================
3. PRINCIPES DE SECURITE
========================================================

Les principes fondamentaux sont :

1. Confidentialité
2. Intégrité
3. Disponibilité
4. Traçabilité
5. Non-répudiation

========================================================
4. GOUVERNANCE SECURITE
========================================================

########################################################
4.1 RESPONSABLE SECURITE
########################################################

Le responsable sécurité doit :

- Superviser la sécurité informatique
- Gérer les incidents
- Contrôler les accès
- Réaliser les audits
- Maintenir la documentation
- Assurer la conformité

########################################################
4.2 UTILISATEURS
########################################################

Chaque utilisateur doit :

- Respecter les politiques internes
- Protéger ses identifiants
- Signaler les incidents
- Utiliser uniquement les logiciels autorisés
- Respecter les règles de mot de passe

========================================================
5. POLITIQUE MOTS DE PASSE
========================================================

Les mots de passe doivent :

- Contenir au minimum 12 caractères
- Inclure majuscules et minuscules
- Inclure chiffres
- Inclure caractères spéciaux
- Être changés régulièrement
- Ne jamais être partagés

Interdictions :
- Mot de passe simple
- Réutilisation
- Stockage non sécurisé

MFA obligatoire pour :
- Administrateurs
- VPN
- Applications critiques

========================================================
6. GESTION DES ACCES
========================================================

########################################################
6.1 PRINCIPE DU MOINDRE PRIVILEGE
########################################################

Chaque utilisateur reçoit uniquement les accès
strictement nécessaires à son activité.

########################################################
6.2 COMPTES ADMINISTRATEURS
########################################################

- Comptes nominatifs obligatoires
- Comptes partagés interdits
- Traçabilité obligatoire
- MFA obligatoire

########################################################
6.3 REVUE DES ACCES
########################################################

Les accès doivent être revus :

- Tous les 3 mois
- Après départ employé
- Après changement poste

========================================================
7. SECURITE RESEAU
========================================================

########################################################
7.1 SEGMENTATION
########################################################

Le réseau doit être segmenté :

- VLAN Administration
- VLAN Utilisateurs
- VLAN Invités
- VLAN Serveurs
- DMZ

########################################################
7.2 FIREWALL
########################################################

Le firewall doit :

- Bloquer tout par défaut
- Autoriser uniquement le nécessaire
- Journaliser les connexions
- Filtrer les flux critiques

########################################################
7.3 VPN
########################################################

Les VPN doivent :

- Utiliser AES256
- Utiliser MFA
- Être journalisés
- Être limités par rôle

========================================================
8. SECURITE POSTES & SERVEURS
========================================================

########################################################
8.1 ANTIVIRUS
########################################################

Tous les postes doivent disposer :

- Antivirus actif
- Mise à jour automatique
- Analyse régulière

########################################################
8.2 MISES A JOUR
########################################################

Les systèmes doivent être mis à jour :

- Correctifs critiques immédiats
- Correctifs mensuels
- Firmware réseau à jour

########################################################
8.3 CHIFFREMENT
########################################################

Le chiffrement est obligatoire pour :

- Ordinateurs portables
- Sauvegardes
- VPN
- Données sensibles

========================================================
9. GESTION DES LOGS
========================================================

Les événements suivants doivent être journalisés :

- Connexions utilisateurs
- Connexions VPN
- Erreurs critiques
- Modifications administrateur
- Détections antivirus
- Alertes IPS

Les logs doivent être :

- Horodatés
- Centralisés
- Conservés minimum 12 mois
- Protégés contre modification

========================================================
10. GESTION DES INCIDENTS
========================================================

########################################################
10.1 DECLARATION
########################################################

Tout incident doit être signalé immédiatement.

########################################################
10.2 CLASSIFICATION
########################################################

Les incidents sont classés :

- Critique
- Elevé
- Moyen
- Faible

########################################################
10.3 REPONSE
########################################################

Les étapes :

1. Détection
2. Analyse
3. Containment
4. Eradication
5. Restauration
6. Retour d’expérience

========================================================
11. SAUVEGARDES
========================================================

Les sauvegardes doivent :

- Être automatiques
- Être chiffrées
- Être testées
- Être externalisées

Règle recommandée :
- 3 copies
- 2 supports différents
- 1 hors site

========================================================
12. CONTINUITE D’ACTIVITE
========================================================

Un PRA/PCA doit exister pour :

- Panne serveur
- Cyberattaque
- Ransomware
- Perte internet
- Catastrophe physique

========================================================
13. SECURITE PHYSIQUE
========================================================

Les salles serveurs doivent :

- Être verrouillées
- Être surveillées
- Être climatisées
- Être protégées contre incendie

========================================================
14. SECURITE EMAIL
========================================================

Les emails doivent être protégés par :

- SPF
- DKIM
- DMARC
- Anti-spam
- Anti-phishing

========================================================
15. SECURITE WEB
========================================================

Les accès web doivent être filtrés :

- Blocage malware
- Blocage phishing
- Blocage contenus dangereux
- Contrôle téléchargements

========================================================
16. UTILISATION ACCEPTABLE
========================================================

Interdictions :

- Logiciels piratés
- Téléchargements illégaux
- Contournement sécurité
- Usage personnel abusif
- Partage comptes

========================================================
17. AUDIT & CONFORMITE
========================================================

Des audits doivent être réalisés :

- Audit sécurité annuel
- Scan vulnérabilités trimestriel
- Test PRA annuel
- Revue accès trimestrielle

========================================================
18. FORMATION SECURITE
========================================================

Tous les employés doivent recevoir :

- Sensibilisation phishing
- Formation cybersécurité
- Procédure incidents
- Bonnes pratiques mots de passe

========================================================
19. SANCTIONS
========================================================

Le non-respect de cette politique peut entraîner :

- Suspension accès
- Sanctions disciplinaires
- Sanctions contractuelles
- Poursuites judiciaires

